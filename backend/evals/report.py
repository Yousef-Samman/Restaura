"""Turns the results into evals/RESULTS.md. Every number in the report comes from latest.json."""


def _pct(x):
    return "n/a" if x is None else f"{x:.1%}"


def _table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def markdown(r: dict) -> str:
    run = r["run"]
    lines = [
        "# Restaura evaluation results",
        "",
        f"Generated by `python -m evals{' --ai' if run['ai_model'] else ''}` on {run['at']} "
        f"({'rules and Claude, model ' + run['ai_model'] if run['ai_model'] else 'rules only, no Claude key'}), in {run['seconds']} s. "
        "Every number below is in `evals/results/latest.json`. How each test works is in the docstring at the top of its file.",
        "",
    ]
    if run.get("ai_at") and run["ai_at"] != run["at"]:
        lines += [f"Claude results are from the last run with Claude, on {run['ai_at']}.", ""]
    t = r.get("tests")
    if t and "total" in t:
        lines += [f"Test suite ({t['at']}): {t['passed']} of {t['total']} tests passed.", ""]
    lines += [
        "## 1. Cashier helper (held out by date)",
        "",
        "Trained on orders before the last 7 days, tested on the last 7 days. A case is a point in a real order where the "
        "customer added more; a hit means one of the two suggestions was an item they really added (hit@2). "
        "Precision: share of all suggestions shown that were bought.",
        "",
    ]
    for scen, s in r["cashier"].items():
        lines += [f"**{scen}** ({next(iter(s['methods'].values()))['cases']} cases, {s['distinct_carts']} different carts)", ""]
        lines.append(_table(["Method", "Hit@2", "Precision"],
                            [[k, _pct(v["hit_at_2"]), _pct(v["precision"])] for k, v in s["methods"].items()]))
        lines.append("")
    lines += [
        "## 2. Sales forecast (walk-forward backtest)",
        "",
        "Each day, forecast the next 7 days from the days before it only, then compare with what sold. "
        "Error = mean absolute percentage error (lower is better). Test window: the last 6 weeks; validation window: "
        "the 6 weeks before. The app's method replaced the previous one after a first look at both windows, so the test "
        "window is not fully untouched; both are shown so the choice can be checked. Real U Walk revenue stays private: "
        "percentages only.",
        "",
    ]
    for data, w in r["forecast"].items():
        head = ["Method", "Validation error", "Test error"]
        lines += [f"**{data}** ({w['test']['days_of_history']} days)", ""]
        lines.append(_table(head, [[k, _pct(w["validation"]["methods"][k]["mape"]), _pct(v["mape"])]
                                   for k, v in w["test"]["methods"].items()]))
        lines.append("")
    st = r["stock"]
    lines += ["## 3. Stock-to-order agent", "", "**Hand-worked scenario** (9 ingredients, 3 suppliers, every correct order worked out by hand)", ""]
    rows = []
    for k in ("rules", "with Claude"):
        if k in st:
            s = st[k]
            rows.append([k, f"{s['correct_lines']}/{s['expected_lines']}", ", ".join(s["missed"] + s["unneeded"] + s["wrong_qty"]) or "none",
                         f"{s['warnings_found']}/{s['warnings_expected']}", s["duplicate_orders_on_second_run"],
                         ", ".join(s.get("ungrounded_numbers", [])) or ("none" if "ungrounded_numbers" in s else "n/a")])
    lines.append(_table(["Path", "Order lines right", "Mistakes", "Warnings raised", "Duplicates on re-run", "Numbers not in the facts"], rows))
    p = st["random_stores"]
    lines += ["", f"**{p['stores']} random stores**: {p['needed_an_order']} needed an order. Recall {_pct(p['recall'])}, "
              f"precision {_pct(p['precision'])}, orders too small to reach par at delivery: {p['orders_too_small']}, "
              f"more than one rounding step too large: {p['orders_too_large']}.", ""]
    lines += ["## 4. Invoice reader", ""]
    inv = r["invoice"]
    if "skipped" in inv:
        lines += ["Skipped: needs the Claude key. Run `python -m evals --ai`.", ""]
    else:
        lines += ["3 drawn invoices with known values (12 lines), each read in 4 conditions. On the smudged one a quantity is "
                  "covered: saying it can't be read, or working it out from the line total, are both right; a wrong number is not.", ""]
        cols = [("line_found", "Lines found"), ("quantity", "Qty"), ("unit_price", "Unit price"), ("line_total", "Line total"),
                ("ingredient_match", "Ingredient match"), ("unit_conversion", "Unit conversion"), ("invoice_total", "Invoice total"),
                ("supplier_and_number", "Supplier + no.")]
        lines.append(_table(["Condition", *[c[1] for c in cols], "Invented lines"],
                            [[cond, *[_pct(v[c[0]]) for c in cols], v["invented_lines"]] for cond, v in inv.items()]))
        sm = inv.get("smudged quantity", {}).get("smudged_quantity", [])
        if sm:
            lines += ["", f"Smudged quantity: said unreadable {sum(a['said_unreadable'] for a in sm)}/{len(sm)}, "
                      f"worked out correctly {sum(a['worked_out_correctly'] for a in sm)}/{len(sm)}, "
                      f"wrong number {sum(a['wrong_number'] for a in sm)}/{len(sm)}."]
        lines.append("")
    return "\n".join(lines)
